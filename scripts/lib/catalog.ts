/**
 * Static catalogue vocabulary used to synthesise a realistic e-commerce data
 * set. Everything here is hand-written (no external services, no Faker) so the
 * generated data reads like a real marketplace rather than "Product 1".
 *
 * Each category exposes `variants`: a product noun plus the modifiers that
 * actually make sense for that noun. This keeps generated names plausible
 * ("Braided USB-C Cable", never "4K Ethernet Cable").
 */

export type Segment =
  | 'electronics'
  | 'accessories'
  | 'home'
  | 'furniture'
  | 'clothing'
  | 'sports'
  | 'books';

export interface CategoryVariant {
  noun: string;
  modifiers: readonly string[];
  priceRange?: [number, number];
}

export interface CategorySeed {
  key: string;
  name: string;
  parentKey: string | null;
  description: string;
  weight: number;
  variants: readonly CategoryVariant[];
  series: readonly string[];
  features: readonly string[];
  materials: readonly string[];
  priceRange: [number, number];
  useCase: string;
  titleStyle?: 'book';
  bookAdjectives?: readonly string[];
  bookTitles?: readonly string[];
  bookFormats?: readonly string[];
}

export interface BrandSeed {
  name: string;
  segments: readonly Segment[];
  country: string;
  foundedYear: number;
  website: string | null;
}

export interface WarehouseSeed {
  warehouseId: string;
  name: string;
  city: string;
  country: string;
  region: 'EMEA' | 'NA';
  capacityUnits: number;
}

export interface Category {
  id: string;
  name: string;
  slug: string;
  parentId: string | null;
  description: string;
}

